#include "../header.h"

int	ft_isdigit(char *c)
{
	int i;
	int ret;

	i = 0;
	ret = 0;
	while (c[i])
	{
		if (c[i] >= '0' && c[i] <= '9')
			ret = 1;
		else
			return (0);
		i++;
	}
	return (ret);
}